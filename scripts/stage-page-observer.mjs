import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chatGPTDOMScript } from '../src/chatgpt-dom.mjs';
import { installPageObserver } from '../src/chatgpt-page-observer.mjs';
export const observerBundle = () => `// Generated by scripts/stage-page-observer.mjs. Edit src/chatgpt-page-observer.mjs.\nconst { ipcRenderer } = require('electron');\nif (process.isMainFrame && location.origin === 'https://chatgpt.com') {\n(${installPageObserver.toString()})(${chatGPTDOMScript()}, message => ipcRenderer.send('pilot:page-observation', message));\n}\n`;
const destination = new URL('../resources/chatgpt-page-observer-preload.cjs', import.meta.url);
await fs.writeFile(destination, observerBundle());
console.log('Page observer staged:', fileURLToPath(destination));
